package com.novel2script.common.enums;

/**
 * Type of a chapter within a novel.
 */
public enum ChapterType {

    /** Standard narrative chapter */
    NORMAL,

    /** Prologue / foreword, appears before chapter 1 */
    PROLOGUE,

    /** Epilogue / afterword, appears after the last chapter */
    EPILOGUE,

    /** Side story / extra / interlude */
    INTERLUDE
}
